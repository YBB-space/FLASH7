assert.ok(Number(ventBranch[1])>Number(regulator[1])+25&&Number(ventBranch[1])<Number(goxValve[1]),'V9 branches between DR75 and V7');
assert.equal(ventBranch[2],goxValve[2],'V9 branches from the GOX supply line');
const goxTap=html.match(/daq-instrument-tap gox" d="M(\d+) (\d+)/);
assert.ok(Number(goxTap[1])>Number(goxValve[1])&&Number(goxTap[1])<engineX&&engineX-Number(goxTap[1])<130,'PT2 taps the GOX line near the engine, downstream of V7');
assert.equal(goxTap[2],goxValve[2]);
