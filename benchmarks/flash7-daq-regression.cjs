const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'ui/shared/document.html'),'utf8')+fs.readFileSync(path.join(root,'ui/shared/daq-control-center.html'),'utf8');
const source=fs.readFileSync(path.join(root,'scripts/flash7-daq.js'),'utf8');
let now=10000;
const nodes=new Map(),logs=[];
const node=()=>({textContent:'',classList:{toggle(){}},style:{setProperty(){}},setAttribute(){},querySelector:()=>null,closest:()=>null});
const context=vm.createContext({
  Date:class extends Date{static now(){return now;}},
  document:{querySelector:()=>null,querySelectorAll:()=>[],getElementById:id=>{if(!nodes.has(id)) nodes.set(id,node());return nodes.get(id);}},
  simEnabled:true,getDisplayOperationModeValue:()=> 'daq',normalizeOperationModeValue:v=>v,
  showToast:message=>logs.push(message),logs
});
vm.runInContext(source,context);
vm.runInContext('appendDaqMockLog=(message)=>logs.push(message);',context);
const run=code=>vm.runInContext(code,context);
const snapshot=code=>JSON.parse(JSON.stringify(run(code)));
const near=(actual,expected,tolerance=1e-9)=>assert.ok(Math.abs(actual-expected)<tolerance,`${actual} != ${expected}`);
const ids=Array.from({length:10},(_,i)=>i+1);
for(const attribute of ['data-daq-valve','data-daq-svg-valve','data-daq-opening']){
  assert.deepEqual([...html.matchAll(new RegExp(attribute+'="(\\d+)"','g'))].map(m=>Number(m[1])).sort((a,b)=>a-b),ids,attribute+' must map every valve once');
}
assert.ok(!html.includes('daqPt2')&&!html.includes('daqSvgPt2'),'removed PT2 cannot remain in the DOM');
assert.ok(!source.includes('daqPt2'),'removed PT2 cannot remain in runtime updates');
const pathFor=name=>html.match(new RegExp('data-daq-flow="'+name+'" d="([^"]+)"'))[1];
const enginePosition=html.match(/daq-engine" transform="translate\((\d+) (\d+)\)"/);
const engineX=Number(enginePosition[1]),engineY=Number(enginePosition[2]);
const sprayPath=pathFor('waterSpray');
const sprayX=Number([...sprayPath.matchAll(/H(\d+)/g)].at(-1)[1]);
const sprayY=Number([...sprayPath.matchAll(/V(\d+)/g)].at(-1)[1]);
assert.ok(sprayX<engineX||sprayY<engineY,'water spray terminates outside the engine');
assert.match(pathFor('ethanolVent'),/H\d+$/,'ethanol vent exits horizontally to the right');
const fuelValve=html.match(/data-daq-svg-valve="3" transform="translate\((\d+) (\d+)\)"/);
const feedTap=html.match(/daq-instrument-tap ethanol" d="M(\d+) (\d+)/);
assert.ok(Number(feedTap[1])>Number(fuelValve[1])&&Number(feedTap[1])<engineX,'PT1 tap is downstream of V3 and upstream of the engine');
assert.equal(feedTap[2],fuelValve[2],'PT1 taps the same ethanol feed segment as V3');
for(const name of [...html.matchAll(/data-daq-flow="([^"]+)"/g)].map(m=>m[1])) assert.ok(name in snapshot('getDaqMockFlows(createDaqMockState())'),'unknown flow segment '+name);
run('resetDaqMockState()');
assert.equal(run('daqMockState.valves.length'),10);
assert.equal(run('requestDaqMockValve(3,37)'),false,'locked commands are rejected');
run('setDaqValveLock(false)');
assert.equal(run('requestDaqMockValve(3,37)'),true);
assert.equal(run('daqMockState.valves[2]'),37,'partial opening is retained');
assert.equal(run('setDaqMockValve(0,100)'),false,'invalid indexes cannot command another valve');
assert.equal(run('setDaqMockValve(11,100)'),false);
assert.equal(run('daqOpening(140)'),100);assert.equal(run('daqOpening(-10)'),0);assert.equal(run('daqOpening(Infinity)'),0);
context.simEnabled=false;assert.equal(run('requestDaqMockValve(3,100)'),false,'live mode cannot accept simulation commands');context.simEnabled=true;
run('stopDaqMockSequence();daqMockState.waterPressure=4.8;daqMockState.ethanolPressure=4.8;setDaqMockValve(2,50,true)');
near(run('getDaqMockFlows(daqMockState).waterSpray'),.5);
assert.equal(run('getDaqMockFlows(daqMockState).combustion'),0,'water spray is independent of combustion');
run('setDaqMockValve(2,0,true);setDaqMockValve(6,100,true)');
const waterLevel=run('daqMockState.waterLevel');
run('advanceDaqMockModel(daqMockState,1)');
assert.ok(run('daqMockState.waterPressure')<4.8,'headspace nitrogen vent relieves water tank pressure');
assert.equal(run('daqMockState.waterLevel'),waterLevel,'nitrogen vent does not drain liquid');
run('setDaqMockValve(6,0,true);setDaqMockValve(8,100,true);advanceDaqMockModel(daqMockState,1)');
assert.ok(run('daqMockState.waterLevel')<waterLevel,'separate water vent drains water');
run('stopDaqMockSequence();setDaqMockValve(10,100,true)');
assert.equal(run('getDaqMockFlows(daqMockState).purgeFeed'),1);
assert.equal(run('getDaqMockFlows(daqMockState).goxFeed'),0);
run('setDaqMockValve(9,100,true)');assert.equal(run('getDaqMockFlows(daqMockState).purgeVent'),1);
run('setDaqMockValve(7,100,true)');assert.equal(run('getDaqMockFlows(daqMockState).purgeFeed'),0,'check valve blocks nitrogen against open GOX supply');
run('stopDaqMockSequence();daqMockState.ethanolPressure=4.8;setDaqMockValve(3,100,true);setDaqMockValve(7,100,true);advanceDaqMockModel(daqMockState,1)');
assert.ok(run('daqMockState.chamberPressure')>0,'chamber instrument follows ethanol and GOX without water');
assert.ok(run('daqMockState.engineTemperature')>20,'engine temperature rises during combustion');
const hot=run('daqMockState.engineTemperature');run('stopDaqMockSequence();advanceDaqMockModel(daqMockState,1)');assert.ok(run('daqMockState.engineTemperature')<hot,'temperature cools after shutdown');
run('const a=createDaqMockState(),b=createDaqMockState();a.valves[0]=b.valves[0]=100;advanceDaqMockModel(a,1);for(let i=0;i<10;i++)advanceDaqMockModel(b,.1)');
near(run('a.waterPressure'),run('b.waterPressure'));
run('resetDaqMockState();daqMockState.armed=true;startDaqMockSequence()');
assert.equal(nodes.get('daqRunReadiness').textContent,'RUNNING');
assert.equal(nodes.get('daqSequenceProgress').textContent,'01 / 05');
assert.equal(run('requestDaqMockValve(5,100)'),false,'automatic sequence owns valve commands');
now+=2000;run('updateDaqMockSequence(Date.now())');assert.equal(run('daqMockState.valves[9]'),100,'purge phase uses V10');assert.equal(run('daqMockState.valves[5]'),0,'purge must not use the water gas vent');
assert.equal(nodes.get('daqSequenceProgress').textContent,'03 / 05');
assert.equal(nodes.get('daqSequenceState').textContent,'PURGE');
now+=2000;run('updateDaqMockSequence(Date.now())');assert.equal(run('daqMockState.valves[9]'),0);assert.equal(run('daqMockState.valves[6]'),100);
now+=5000;run('updateDaqMockSequence(Date.now())');assert.ok(run('daqMockState.valves.every(v=>v===0)'));assert.equal(run('daqMockState.running'),false);
assert.equal(nodes.get('daqRunReadiness').textContent,'COMPLETE');
assert.equal(nodes.get('daqSequenceProgress').textContent,'05 / 05');
run('resetDaqMockState();daqMockState.armed=true;startDaqMockSequence()');now+=4000;run('updateDaqMockSequence(Date.now())');
assert.deepEqual(snapshot('daqMockState.valves'),[100,100,100,100,0,0,100,0,0,0],'skipped phases apply complete targets');
run('abortDaqMockSequence()');assert.ok(run('daqMockState.valves.every(v=>v===0)'));assert.equal(run('daqMockState.sequenceElapsedMs'),0);
assert.equal(nodes.get('daqRunReadiness').textContent,'READY');
assert.equal(nodes.get('daqSequenceProgress').textContent,'01 / 05');
assert.equal(nodes.get('daqSequenceState').textContent,'STANDBY');
run('updateDaqMockUi(true)');assert.equal(nodes.get('daqSvgPt1').textContent,'0.00');assert.ok(Number.isFinite(Number(nodes.get('daqEngineTemp').textContent)));
console.log('FLASH7 DAQ: PASS (10-valve mapping, percent commands, interlocks, water outlets, vents, purge isolation, time-based pressures/temperature, phase skipping and abort)');
